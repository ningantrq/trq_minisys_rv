// ========================================================================
// 七段数码管显示外设模块
// ========================================================================
// 功能说明：
//   - 接收32位数据（8个4位BCD码），控制8个数码管显示不同内容
//   - 支持共阴极数码管（低电平点亮对应段）
//   - 使用时分复用技术，以2ms刷新率依次扫描8个数码管
//
// 接口说明：
//   - clk_i: 系统时钟输入
//   - rst_i: 复位信号（高电平有效）
//   - wr_i: 写使能信号
//   - seg_data_i[31:0]: 8个BCD数据（每4位控制一个数码管，[3:0]对应数码管0，[31:28]对应数码管7）
//   - seg_an_o[7:0]: 数码管片选信号（低电平选中，每次仅一个数码管使能）
//   - seg_out_o[7:0]: 七段显示码输出 (DP G F E D C B A)
//
// 七段数码管段位定义：
//       A
//      ---
//   F |   | B
//      -G-
//   E |   | C
//      ---
//       D   DP
// ========================================================================
module peri_seg (
    input clk_i,
    input rst_i,
    
    input wr_i,
    input [31:0] seg_data_i,
    
    output reg [7:0] seg_an_o,
    output reg [7:0] seg_out_o
);

// ========================================================================
// 数据寄存器
// ========================================================================
// 锁存要显示的32位BCD数据（8个数码管的数据）
reg [31:0] seg_data_r;

always @(posedge clk_i or posedge rst_i) begin
    if (rst_i)
        seg_data_r <= 32'h0;  // 复位时显示全0
    else if (wr_i)
        seg_data_r <= seg_data_i;  // 写使能时更新显示数据
end

// ========================================================================
// 时分复用刷新控制
// ========================================================================
// 假设系统时钟为100MHz，2ms刷新一次需要计数到200,000
// 8个数码管轮流显示，每个数码管显示时间约为250us (2ms/8)
parameter REFRESH_CNT_MAX = 25000;  // 100MHz / 25000 = 4KHz，每个数码管250us

reg [15:0] refresh_cnt_r;  // 刷新计数器
reg [2:0] display_idx_r;   // 当前显示的数码管索引（0-7）

// 刷新计数器和数码管索引控制
always @(posedge clk_i or posedge rst_i) begin
    if (rst_i) begin
        refresh_cnt_r <= 16'h0;
        display_idx_r <= 3'h0;
    end else begin
        if (refresh_cnt_r >= REFRESH_CNT_MAX - 1) begin
            refresh_cnt_r <= 16'h0;
            display_idx_r <= display_idx_r + 1'b1;  // 切换到下一个数码管
        end else begin
            refresh_cnt_r <= refresh_cnt_r + 1'b1;
        end
    end
end

// ========================================================================
// 数码管片选控制
// ========================================================================
// 根据当前索引，仅使能一个数码管（低电平有效）
always @(*) begin
    case (display_idx_r)
        3'h0: seg_an_o = 8'b11111110;  // 使能数码管0
        3'h1: seg_an_o = 8'b11111101;  // 使能数码管1
        3'h2: seg_an_o = 8'b11111011;  // 使能数码管2
        3'h3: seg_an_o = 8'b11110111;  // 使能数码管3
        3'h4: seg_an_o = 8'b11101111;  // 使能数码管4
        3'h5: seg_an_o = 8'b11011111;  // 使能数码管5
        3'h6: seg_an_o = 8'b10111111;  // 使能数码管6
        3'h7: seg_an_o = 8'b01111111;  // 使能数码管7
        default: seg_an_o = 8'b11111111;  // 默认全不使能
    endcase
end

// ========================================================================
// 当前数码管数据选择
// ========================================================================
// 根据当前索引，从32位数据中选择对应的4位BCD码
reg [3:0] current_bcd_r;

always @(*) begin
    case (display_idx_r)
        3'h0: current_bcd_r = seg_data_r[3:0];    // 数码管0
        3'h1: current_bcd_r = seg_data_r[7:4];    // 数码管1
        3'h2: current_bcd_r = seg_data_r[11:8];   // 数码管2
        3'h3: current_bcd_r = seg_data_r[15:12];  // 数码管3
        3'h4: current_bcd_r = seg_data_r[19:16];  // 数码管4
        3'h5: current_bcd_r = seg_data_r[23:20];  // 数码管5
        3'h6: current_bcd_r = seg_data_r[27:24];  // 数码管6
        3'h7: current_bcd_r = seg_data_r[31:28];  // 数码管7
        default: current_bcd_r = 4'h0;
    endcase
end

// ========================================================================
// BCD到七段码译码
// ========================================================================
// 将4位BCD码转换为七段显示码
// 段编码格式：{DP, G, F, E, D, C, B, A}
// 0表示点亮该段（共阴极），1表示熄灭
always @(*) begin
    case (current_bcd_r)
        4'h0: seg_out_o = 8'b01000000;  // 0: 显示 "0"
        4'h1: seg_out_o = 8'b01111001;  // 1: 显示 "1"
        4'h2: seg_out_o = 8'b00100100;  // 2: 显示 "2"
        4'h3: seg_out_o = 8'b00110000;  // 3: 显示 "3"
        4'h4: seg_out_o = 8'b00011001;  // 4: 显示 "4"
        4'h5: seg_out_o = 8'b00010010;  // 5: 显示 "5"
        4'h6: seg_out_o = 8'b00000010;  // 6: 显示 "6"
        4'h7: seg_out_o = 8'b01111000;  // 7: 显示 "7"
        4'h8: seg_out_o = 8'b00000000;  // 8: 显示 "8"
        4'h9: seg_out_o = 8'b00010000;  // 9: 显示 "9"
        4'ha: seg_out_o = 8'b00001000;  // A: 显示 "A"
        4'hb: seg_out_o = 8'b00000011;  // b: 显示 "b"
        4'hc: seg_out_o = 8'b01000110;  // c: 显示 "C"
        4'hd: seg_out_o = 8'b00100001;  // d: 显示 "d"
        4'he: seg_out_o = 8'b00000110;  // E: 显示 "E"
        4'hf: seg_out_o = 8'b00001110;  // F: 显示 "F"
        default: seg_out_o = 8'b00000000;  // 默认全亮
    endcase
end

endmodule
