#include "keyboard.h"
#include "seg.h"

void delay();

// ========================================================================
// 键盘数码管交互测试程序（适配阻塞式键盘）
// ========================================================================
// 功能说明：
//   连续读取8次键盘输入，每次按键后将值累加到数码管显示
//   充分展示了新的阻塞式键盘特性：
//     - CPU在keyboard_read()处自动等待按键
//     - 无需轮询检查按键是否有效
//     - 每次读取保证返回有效按键值
//
// 使用方式：
//   1. 程序启动后显示初始值 0x12345678
//   2. 短暂延迟后清空显示，等待用户输入
//   3. 依次按下8个按键（0-F），每次按键后数码管立即更新显示
//   4. 输入完成后显示完整的8位十六进制数
//   5. 程序重新开始，等待下一轮输入
// ========================================================================

int main() {
  seg_display_all(0x12345678);
  delay();
  
  while (1) {
    unsigned int display_val = 0;
    
    seg_clear();
    
    for (int i = 0; i < 8; i++) {
      int key = keyboard_read();
      
      display_val = (display_val << 4) | (key & 0xF);
      seg_display_hex(display_val);
      
      delay();
    }
    
    delay();
    delay();
  }
  
  return 0;
}

void delay() {
  for (int i = 0; i < 500000; ++i) {
    asm volatile("nop");
  }
}
